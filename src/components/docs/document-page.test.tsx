it("saves local-only Markdown without querying or creating a workspace row", async () => {
  const { writeVaultFile } = await import('@/lib/vault');
  data.getWorkspaceRecord.mockClear(); data.updateWorkspaceRecord.mockClear();
  vi.mocked(readVaultFile).mockResolvedValue('# Local note\n\nOriginal');
  vi.mocked(writeVaultFile).mockResolvedValue(undefined);
  const host = document.createElement('div'); document.body.append(host); root = createRoot(host);
  client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  await act(async () => root.render(<MemoryRouter><QueryClientProvider client={client}><DocumentPage record={{ id:'vault:journal/local.md', _vaultOnly:true, doc_title:'Local note', doc_vault_path:'vault:journal/local.md' }} projects={[]} initialEdit={false} savingTemplate={false} isCramped={false} onBack={vi.fn()} onSaveTemplate={vi.fn()} onDelete={vi.fn()} onMakeRunnable={vi.fn()} /></QueryClientProvider></MemoryRouter>));
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 20)); });
  await act(async () => { const session = documentSaveSessions.get('vault:journal/local.md')!; session.edit('# Local note\n\nEdited'); await session.flush(); });
  expect(writeVaultFile).toHaveBeenCalledWith('vault:journal/local.md','# Local note\n\nEdited');
  expect(data.getWorkspaceRecord).not.toHaveBeenCalled(); expect(data.updateWorkspaceRecord).not.toHaveBeenCalled();
  expect(host.querySelector('[aria-label="Document menu"]')).toBeNull();
});
it("preserves an open draft instead of overwriting an external file edit", async () => {
  const { writeVaultFile } = await import('@/lib/vault'); vi.mocked(writeVaultFile).mockClear();
  vi.mocked(readVaultFile).mockResolvedValueOnce('# Local\n\nOriginal').mockResolvedValue('# Local\n\nExternal edit');
  const host = document.createElement('div'); document.body.append(host); root = createRoot(host);
  client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  await act(async () => root.render(<MemoryRouter><QueryClientProvider client={client}><DocumentPage record={{ id:'vault:journal/conflict.md', _vaultOnly:true, doc_title:'Local', doc_vault_path:'vault:journal/conflict.md' }} projects={[]} initialEdit={false} savingTemplate={false} isCramped={false} onBack={vi.fn()} onSaveTemplate={vi.fn()} onDelete={vi.fn()} onMakeRunnable={vi.fn()} /></QueryClientProvider></MemoryRouter>));
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 20)); });
  await act(async () => { const session = documentSaveSessions.get('vault:journal/conflict.md')!; session.edit('# Local\n\nMy draft'); await session.flush(); });
  expect(writeVaultFile).not.toHaveBeenCalled(); expect(host.textContent).toContain('changed outside the editor');
  expect(localStorage.getItem('intelizen:document-draft:vault:journal/conflict.md')).toContain('My draft');
});
